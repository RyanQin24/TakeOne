"""Effect primitives. Every look, template and AI decision compiles down to these.

A primitive is the smallest unit the render backend knows how to execute. Adding one means
adding a spec here and a fragment function in `render/ffmpeg.py`; nothing else changes.
Deliberately small: twenty-four well-chosen primitives support far more creative range than
two hundred hard-coded effects, and each one is independently testable.
"""

from ..operations import ParamSpec as P
from .spec import EffectSpec


def _spec(identifier, name, category, parameters, description, tags=()):
    return EffectSpec(
        id=identifier,
        version=1,
        name=name,
        category=category,
        parameters=tuple(parameters),
        arity=1,
        primitive=True,
        description=description,
        tags=tuple(tags),
    )


